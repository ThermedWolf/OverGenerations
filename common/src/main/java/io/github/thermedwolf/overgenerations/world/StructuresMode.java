package io.github.thermedwolf.overgenerations.world;

/**
 * Which structures a world uses.
 */
public enum StructuresMode {

    /** Vanilla structures plus OverGenerations-only builds (ruins, hidden stories, ...). */
    ALL,

    /** OverGenerations structures that replace vanilla equivalents (villages, ...). */
    NORMAL_ONLY,

    /** Vanilla structures only; OverGenerations adds nothing. */
    OFF
}
